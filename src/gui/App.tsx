/**
 * SlicyWeb
 * App
 *
 * Main application component: assembles the main window
 * (GUI_SPEC.md, Main Window) in MainLayout:
 * Menu Bar, Toolbar, Object Panel, Viewport, Properties Panel,
 * Status Bar.
 *
 * DirectionProvider gives the text direction of the current language
 * to the Base UI components (menus): keyboard navigation and popup
 * placement follow right-to-left in Hebrew.
 *
 * Texts come from the translation dictionaries (useTranslation).
 *
 * The viewport receives the function that applies a transform
 * (TransformService, Phase 6): gizmos and dragging on the plate.
 * The buttons Move, Rotate, Scale (TransformModeBar) are shown over the
 * viewport, in the top row of the drop zone, before the messages (lot 104). Undo and redo: Ctrl+Z, Ctrl+Y, Ctrl+Shift+Z
 * (useUndoRedoShortcuts), toolbar and Edit menu (TransformService).
 * Ctrl+A selects all the objects (useSelectAllShortcut). Delete and
 * Ctrl+D delete and duplicate the selected objects (useEditShortcuts, lot
 * 100); several objects are deleted after a confirmation
 * (DeleteObjectsDialog). F2, H and Alt+H rename, hide and show all
 * (useObjectStateShortcuts, lot 106); a rename opens the Object Panel
 * when it is collapsed.
 *
 * At start, the printers loaded by the main process are read, and the
 * last printer is selected again (PrinterSelectionService, Phase 7).
 * The Printer Manager (PrinterManagerDialog) adds, changes and removes
 * the printers entered by the user (Phase 7 lot 61); the Filament
 * Manager (FilamentManagerDialog) the filaments entered by the user
 * (Phase 8 lot 71).
 *
 * The analysis of the objects starts by itself (AnalysisService, Phase 9
 * lot 80): after the import of each object, and when its analysis
 * becomes outdated (ADR-034 D7).
 *
 * The presets loaded by the main process are read at start, and the
 * recommendation of each object is generated by itself (Recommendation
 * Service, Phase 10 lot 88): once its analysis is up to date and a printer
 * and a material are selected, and again after a change of the selection
 * or of the object type (ADR-035 D11).
 *
 * The objects out of the build volume are found as soon as they go out
 * (PlateCheckService, lot 101): orange in the viewport, warning icon in
 * the Object Panel, message over the viewport.
 *
 * The Printer tab of the Properties Panel is open at every start (lot 95,
 * Q3 B: the tab is not saved).
 *
 * The right click without drag in the viewport opens the context menu
 * (ContextMenu, lot 105): of the selection on an object, of the scene in
 * the empty space.
 *
 * The project (Phase 13, lot 111, ADR-038): ProjectService starts at
 * start (recent projects, recovery of a copy of the automatic save,
 * automatic save, close of the window); the title of the window is the
 * name of the project, with "•" when it is modified (Q12 A); Ctrl+N,
 * Ctrl+O, Ctrl+S and Ctrl+Shift+S (useProjectShortcuts); the windows
 * "Save the changes?" (UnsavedChangesDialog) and the recovery
 * (RecoveryDialog).
 *
 * Based on:
 * - ARCHITECTURE.md
 * - GUI_SPEC.md
 * - FILE_STRUCTURE.md
 */

import { useEffect } from "react";
import { DirectionProvider } from "@base-ui/react/direction-provider";

import { formatQuantities } from "../i18n/NumberFormatter";
import { AnalysisService } from "../services/AnalysisService";
import { CostEstimationService } from "../services/CostEstimationService";
import { CostSettingsService } from "../services/CostSettingsService";
import { MaterialSelectionService } from "../services/MaterialSelectionService";
import { PlateCheckService } from "../services/PlateCheckService";
import { PrinterSelectionService } from "../services/PrinterSelectionService";
import { ProjectService } from "../services/ProjectService";
import { RecommendationService } from "../services/RecommendationService";
import { TransformService } from "../services/TransformService";
import { usePrinterStore } from "../state/printerStore";
import { useIsModified, useProjectStore } from "../state/projectStore";

import MainLayout from "./MainLayout";
import DeleteObjectsDialog from "./dialogs/DeleteObjectsDialog";
import FilamentManagerDialog from "./dialogs/FilamentManagerDialog";
import PrinterManagerDialog from "./dialogs/PrinterManagerDialog";
import RecoveryDialog from "./dialogs/RecoveryDialog";
import UnsavedChangesDialog from "./dialogs/UnsavedChangesDialog";
import { useEditShortcuts } from "./hooks/useEditShortcuts";
import { useObjectStateShortcuts } from "./hooks/useObjectStateShortcuts";
import { useProjectShortcuts } from "./hooks/useProjectShortcuts";
import { useTranslation } from "./hooks/useTranslation";
import { useSelectAllShortcut } from "./hooks/useSelectAllShortcut";
import { useUndoRedoShortcuts } from "./hooks/useUndoRedoShortcuts";
import ContextMenu, { openContextMenu } from "./menus/ContextMenu";
import MenuBar from "./menus/MenuBar";
import LeftSidebar from "./sidebar/LeftSidebar";
import { useRenameStore } from "./sidebar/renameStore";
import RightSidebar from "./sidebar/RightSidebar";
import StatusBar from "./statusbar/StatusBar";
import Toolbar from "./toolbars/Toolbar";
import TransformModeBar from "./toolbars/TransformModeBar";
import ImportDropZone from "./import/ImportDropZone";
import Viewport from "./viewport/Viewport";
import { projectDisplayName } from "./project/projectFormat";

export default function App(): JSX.Element {
  const { t, direction, language } = useTranslation();
  const printer = usePrinterStore((state) => state.selectedPrinter);
  const buildVolume = usePrinterStore(
    (state) => state.selectedPrinter?.buildVolume ?? null,
  );
  useUndoRedoShortcuts();
  useSelectAllShortcut();
  useEditShortcuts();
  useObjectStateShortcuts();
  useProjectShortcuts();
  const projectName = useProjectStore((state) => state.projectName);
  const modified = useIsModified();
  const renameRequest = useRenameStore((state) => state.request);

  // Title of the window (lot 111, Q12 A): "• cube — SlicyWeb" when the
  // project is modified
  const title = `${modified ? "• " : ""}${projectDisplayName(
    projectName,
    t("project.untitled"),
  )} — SlicyWeb`;

  useEffect(() => {
    document.title = title;
  }, [title]);

  // Texts of the Windows dialogs of the project, in the language shown
  useEffect(() => {
    ProjectService.setDialogTexts({
      openTitle: t("project.dialog.openTitle"),
      saveTitle: t("project.dialog.saveTitle"),
      filterName: t("project.dialog.filterName"),
    });
  }, [t]);

  useEffect(() => {
    void PrinterSelectionService.load();
    void MaterialSelectionService.load();
    void RecommendationService.loadPresets();
    void CostSettingsService.load();
  }, []);

  useEffect(() => AnalysisService.start(), []);

  useEffect(() => RecommendationService.start(), []);

  useEffect(() => PlateCheckService.start(), []);

  useEffect(() => CostEstimationService.start(), []);

  useEffect(() => ProjectService.start(), []);

  const header = (
    <header className="shrink-0">
      <div className="flex h-9 items-center gap-3 border-b border-border bg-card px-3">
        <span className="text-sm font-semibold">SlicyWeb</span>
        <MenuBar />
      </div>

      <Toolbar />
    </header>
  );

  return (
    <DirectionProvider direction={direction}>
      <MainLayout
        header={header}
        leftTitle={t("objects.title")}
        leftPanel={<LeftSidebar />}
        leftExpandRequest={renameRequest}
        centerPanel={
          <ImportDropZone toolbar={<TransformModeBar />}>
            <Viewport
              label={t("viewport.title")}
              unavailableMessage={t("viewport.unavailable")}
              plateLabel={
                buildVolume
                  ? t("viewport.plate", {
                      size: formatQuantities(
                        [buildVolume.x, buildVolume.y],
                        " × ",
                        "mm",
                        language,
                      ),
                    })
                  : null
              }
              printerName={printer ? `${printer.brand} ${printer.model}` : null}
              cubeLabels={{
                top: t("viewCube.top"),
                bottom: t("viewCube.bottom"),
                front: t("viewCube.front"),
                back: t("viewCube.back"),
                left: t("viewCube.left"),
                right: t("viewCube.right"),
              }}
              onTransformObjects={(transforms, live) =>
                TransformService.applyMany(transforms, { live })
              }
              onTransformGesture={(objectIds, phase) =>
                phase === "start"
                  ? TransformService.beginGesture(objectIds)
                  : TransformService.endGesture()
              }
              onContextMenu={(objectId, x, y) =>
                openContextMenu(objectId ? "object" : "scene", { x, y })
              }
            />
          </ImportDropZone>
        }
        rightTitle={t("properties.title")}
        rightPanel={<RightSidebar />}
        statusBar={<StatusBar />}
      />
      <PrinterManagerDialog />
      <FilamentManagerDialog />
      <DeleteObjectsDialog />
      <UnsavedChangesDialog />
      <RecoveryDialog />
      <ContextMenu />
    </DirectionProvider>
  );
}
